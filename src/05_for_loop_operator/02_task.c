#include <stdio.h>  // Подключаем библиотеку для ввода/вывода
#include <stdlib.h> // Подключаем библиотеку для exit
int main()
{
    int n, sum = 0;

    // Ввод количества чисел
    printf("Введите количество четных чисел n: ");
    scanf("%d", &n);

    // Проверка корректности ввода
    if (n <= 0)
    {
        printf("Ошибка: n должно быть положительным.\n");
        exit(1); // Завершаем программу с кодом ошибки
    }

    // Суммирование первых n четных чисел
    for (int i = 1; i <= n; i++)
    {
        sum += 2 * i; // i-е чётное число = 2*i
    }

    printf("Сумма первых %d четких чисел = %d\n", n, sum);

    return 0; // Успешное завершение программы
}