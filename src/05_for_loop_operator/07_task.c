#include <stdio.h>  // Подключаем библиотеку для ввода/вывода
#include <stdlib.h> // Подключаем библиотеку для exit

int main()
{
    int n = 10; // Переменная для размера таблицы

    // Выводим заголовк таблицы
    printf("Таблица умножения от 1 до %d:\n\n", n);
    printf("    "); // Отступ для первой колонки

    for (int i = 1; i <= n; i++)
    {
        printf("%4d", i); // Выводим номера столбцов с шириной 4 символа
    }

    printf("\n");

    // Рисуем разделительную линию
    printf("   +");

    for (int i = 1; i <= n; i++)
    {
        printf("----");
    }

    printf("\n");

    // Основная часть: строки таблицы
    for (int i = 1; i <= n; i++)
    {
        printf("%2d |", i); // Номер текущей строки
        for (int j = 1; j <= n; j++)
        {
            printf("%4d", i * j);
        }
        printf("\n");
    }

    return 0; // Успешное завершение программы
}