#include <stdio.h>  // Подключаем библиотеку для ввода и вывода
#include <stdlib.h> // Подключаем библиотеку для функции rand
#include <time.h>   // Подключаем библиотеку для функции time

int main()
{
    int size; // Переменная для хранения количества элементов массива

    // Ввод количества элементов массива
    printf("Введите количество элементов массива: ");
    scanf("%d", &size);

    // Проверка корректности ввода
    if (size <= 0)
    {
        printf("Ошибка: элементы массива должны быть положительными.\n");
        exit(1); // Завершаем программу с кодом ошибки
    }

    if (size < 3)
    {
        printf("Ошибка: для вычислений нужно минимум 3 элемента.\n");
        exit(1); // Завершаем программу с кодом ошибки
    }

    int arr[size]; // Массив переменной длинны

    // Инициализация генератора случайных чисел
    srand(time(NULL));

    // Заполнение массива случайными числами от 1 до 99
    printf("Сгенерированный массив: ");
    for (int i = 0; i < size; i++)
    {
        arr[i] = rand() % 100;
        printf("%d ", arr[i]);
    }

    printf("\n"); // Отступ

    // Поиск минимального и максимального значения
    int min = arr[0]; // Первый элемент массива считаем сразу минимальным и максимальным
    int max = arr[0];
    for (int i = 1; i < size; i++)
    {
        if (arr[i] < min)
        {
            min = arr[i];
        }
        if (arr[i] > max)
        {
            max = arr[i];
        }
    }

    // Подсчет суммы и количество элементов, не равных min и max
    int sum = 0;
    int count = 0;
    for (int i = 0; i < size; i++)
    {
        if (arr[i] != min && arr[i] != max)
        {
            sum += arr[i];
            count++;
        }
    }

    // Проверка остались ли элементы после удаления min и max
    if (count == 0)
    {
        printf("После удаления всех минимальных и максимальных элементов массив стал пустым.\n");
        exit(1); // Завершаем программу с кодом ошибки
    }

    // Подсчет среднего значения и вывод результатов
    double average = (double)sum / count;
    printf("Минимальное значение: %d\n", min);
    printf("Максимальное значение: %d\n", max);
    printf("Среднее арифметическое значение (без учета минимального и максимального): %.2f\n", average);

    return 0; // Успешное завершение программы
}