#include <stdio.h>

int main()
{
    // 1. Ввод числа (используем unsigned int для битовых операций)
    unsigned int num;
    printf("Введите целое неотрицательное число: ");
    // Проверяем, что ввод корректен
    if (scanf("%u", &num) != 1)
    {
        printf("Ошибка ввода. Пожалуйста, введите целое число.\n");
        return 1;
    }

    // 2. Номер бита (считаем с 1 – первый бит самый младший)
    int bit_position = 10;

    // 3. Создаём маску: единица на позиции bit_position-1 (т.к. нумерация с 0)
    unsigned int mask = 1u << (bit_position - 1); // 1u гарантирует unsigned

    // 4. Проверяем, установлен ли бит
    if (num & mask)
    {
        printf("%d-й бит числа %u установлен (1)\n", bit_position, num);
    }
    else
    {
        printf("%d-й бит числа %u не установлен (0)\n", bit_position, num);
    }

    // 5. Вывод полного 32-битного двоичного представления
    printf("Двоичное представление (32 бита):\n");
    // Проходим по битам от 31 (старший) до 0 (младший)
    for (int i = 31; i >= 0; i--)
    {
        // (num >> i) & 1 – выделяем i-й бит
        printf("%d", (num >> i) & 1);
        // Каждые 4 бита добавляем пробел для читаемости (кроме последнего)
        if (i % 4 == 0 && i != 0)
        {
            printf(" ");
        }
    }
    printf("\n");

    return 0;
}