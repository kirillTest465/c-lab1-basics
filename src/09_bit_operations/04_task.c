#include <stdio.h> // Подключаем библиотеку для ввода и вывода

int main()
{
    unsigned int num; // Используем беззнаковый тип для предсказуемого сдвига вправо

    printf("Введите целое неотрицательное число: ");
    if (scanf("%u", &num) != 1)
    {
        printf("Ошибка ввода!\n");
        return 1; // Завершаем программу с кодом ошибки
    }

    printf("Битовый образ числа %u (32 бита):\n", num);
    for (int i = 31; i >= 0; i--)
    {
        printf("%d", (num >> i) & 1);

        // Добавляем пробелы каждые 4 бита
        if (i % 4 == 0 && i != 0)
        {
            printf(" ");
        }
    }

    printf("\n");

    return 0; // Успешно завершаем программу
}