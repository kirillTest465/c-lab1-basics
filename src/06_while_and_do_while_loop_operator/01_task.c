/*
a) for ( ; e2 ; ) S; и while ( e2 ) S; — эквивалентны.
В for пропущены инициализация и выражение после итерации, поэтому он сводится к проверке условия e2 перед каждым выполнением тела S. Это в точности соответствует работе while.

b) for ( ; ; ) S; и while (1) S; — эквивалентны.
Оба представляют собой бесконечный цикл: в for отсутствует условие (по умолчанию истина), а в while условие 1 всегда истинно. Тело S будет выполняться бесконечно в обоих случаях.
*/