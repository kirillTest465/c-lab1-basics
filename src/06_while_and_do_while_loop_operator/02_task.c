#include <stdio.h> // Подключаем библиотеку для ввода и вывода

int main()
{

    int num;       // Переменная хранения ввода числа с клавиатуры
    int min;       // Переменная для хранения минимума
    int first = 1; // Флаг: было ли уже введенно положительное число

    printf("Введите последовательность положительных чисел (0 для окончания ввода)\n");

    while (1)
    {

        scanf("%d", &num);

        if (num == 0)
        {
            break;
        }

        if (num < 0)
        {
            printf("Ошибка: Вы введли отрицательное число %d. Попробуйте снова!\n", num);
            continue; // Пропускаем отрицательные числа
        }

        if (first)
        {
            min = num; // Первое положительно число становится минимальным
            first = 0;
        }
        else if (num < min)
        {
            min = num; // Обновляем минимум
        }
    }

    // Вывод результата
    if (first)
    {
        printf("Не было введенно ни одного положительного числа.\n");
    }
    else
    {
        printf("Минимально число: %d\n", min);
    }

    return 0; // Успешное завершение программы
}