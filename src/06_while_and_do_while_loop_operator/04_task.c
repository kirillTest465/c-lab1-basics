#include <stdio.h>
#include <math.h> // для fabs

int main()
{
    double epsilon;     // заданная точность
    double sum = 0.0;   // сумма ряда (π/4)
    int sign = 1;       // знак текущего члена (+1 или -1)
    double denom = 1.0; // знаменатель (начинаем с 1)
    double term;        // очередной член ряда

    // Ввод точности
    printf("Введите точность (например, 0.0001): ");
    scanf("%lf", &epsilon);

    // Проверка корректности
    if (epsilon <= 0)
    {
        printf("Ошибка: точность должна быть положительным числом.\n");
        return 1;
    }

    // Суммирование ряда
    while (1)
    {
        term = sign * (1.0 / denom);
        sum += term;
        sign = -sign; // меняем знак для следующего члена
        denom += 2.0; // следующий нечётный знаменатель

        // Проверяем, нужно ли продолжать
        // Смотрим модуль следующего члена (он равен 1/denom)
        if ((1.0 / denom) < epsilon)
        {
            break;
        }
    }

    // Вычисляем π
    double pi = 4.0 * sum;

    // Вывод результата
    printf("Приближенное значение π = %.10f\n", pi);
    printf("Вычислено с точностью %f\n", epsilon);

    return 0;
}